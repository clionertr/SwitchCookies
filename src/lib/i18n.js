let currentLang = 'en-US';

export function resolveLang(pref) {
  if (pref && pref !== 'auto' && DICT[pref]) return pref;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function setLang(lang) {
  currentLang = DICT[lang] ? lang : 'en-US';
  // Service Worker 里没有 document，仅在页面环境同步 <html lang>
  if (typeof document !== 'undefined') document.documentElement.lang = currentLang;
}

export function getLang() {
  return currentLang;
}

/** 取文案并插值：t('saved', { name: 'A' }) */
export function t(key, vars) {
  let s = DICT[currentLang]?.[key] ?? DICT['en-US'][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** 把 data-i18n / data-i18n-placeholder / data-i18n-title 应用到 DOM 子树。 */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}